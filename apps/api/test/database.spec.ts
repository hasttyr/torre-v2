import { readdirSync, readFileSync } from 'node:fs';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { execute } from './support/postgres.js';
import { createTestDatabase } from './support/test-database.js';
import type { TestDatabase } from './support/test-database.js';

const MIGRATIONS = new URL('../prisma/migrations/', import.meta.url);
const migrationNames = (): string[] =>
  readdirSync(MIGRATIONS, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

/** First row of a query as the given role. */
async function queryOne<T>(url: string, sql: string): Promise<T> {
  const { default: pg } = await import('pg');
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    return (await client.query(sql)).rows[0] as T;
  } finally {
    await client.end();
  }
}

let db: TestDatabase;

beforeAll(async () => {
  db = await createTestDatabase();
});

afterAll(async () => {
  await db.dispose();
});

describe('migrations', () => {
  it('[US-007:AC1] should apply every versioned SQL migration from an empty database', async () => {
    const applied = await queryOne<{ names: string[] }>(
      db.migrationUrl,
      'SELECT array_agg(migration_name ORDER BY migration_name) AS names FROM _prisma_migrations WHERE finished_at IS NOT NULL AND rolled_back_at IS NULL',
    );

    expect(migrationNames().length).toBeGreaterThan(0);
    expect(applied.names).toEqual(migrationNames());
    for (const name of migrationNames()) {
      expect(readFileSync(new URL(`${name}/migration.sql`, MIGRATIONS), 'utf8').trim()).not.toBe('');
    }
  });

  it('[US-007:AC2] should leave the tables to the migration role and the history out of the application role', async () => {
    const owner = await queryOne<{ owner: string }>(
      db.migrationUrl,
      "SELECT tableowner AS owner FROM pg_tables WHERE schemaname = 'public' AND tablename = 'institutions'",
    );

    expect(owner.owner).toBe('torre_migrator');
    await expect(execute(db.appUrl, 'SELECT count(*) FROM _prisma_migrations')).rejects.toThrow(/permission denied/);
  });
});

describe('application role', () => {
  it('[US-007:AC1] should run a minimal create, read and update through Prisma', async () => {
    const created = await db.prisma.institution.create({ data: { name: 'Universidad de Prueba', city: 'Cali' } });
    const updated = await db.prisma.institution.update({ where: { id: created.id }, data: { city: 'Palmira' } });
    const found = await db.prisma.institution.findUniqueOrThrow({ where: { id: created.id } });

    // UUID v7 generated by the server (DEC-026): version nibble 7.
    expect(created.id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
    expect(updated.city).toBe('Palmira');
    expect(found).toMatchObject({ name: 'Universidad de Prueba', city: 'Palmira', sniesCode: null, deletedAt: null });
  });

  it('[US-007:AC2] should not delete rows nor change the schema: only the migration role does', async () => {
    const { id } = await db.prisma.institution.create({ data: { name: 'Universidad Borrable', city: 'Pasto' } });

    await expect(db.prisma.institution.delete({ where: { id } })).rejects.toThrow(/permission denied|denied/i);
    await expect(execute(db.appUrl, 'CREATE TABLE intruder (id int)')).rejects.toThrow(/permission denied/);
    await expect(execute(db.migrationUrl, 'CREATE TABLE allowed_for_migrations (id int)')).resolves.toBeUndefined();
    expect(await db.prisma.institution.count({ where: { id } })).toBe(1);
  });
});

describe('plan case TC-045', () => {
  it('[TC-045] should build the schema from an empty database, serve a minimal CRUD and leave migrating to the migration role', async () => {
    const applied = await queryOne<{ total: number }>(
      db.migrationUrl,
      'SELECT count(*)::int AS total FROM _prisma_migrations WHERE finished_at IS NOT NULL AND rolled_back_at IS NULL',
    );
    const created = await db.prisma.institution.create({ data: { name: 'Universidad TC-045', city: 'Tunja' } });
    const read = await db.prisma.institution.findUniqueOrThrow({ where: { id: created.id } });

    expect(applied.total).toBe(migrationNames().length);
    expect(read.name).toBe('Universidad TC-045');
    await expect(execute(db.appUrl, 'CREATE TABLE tc045_intruder (id int)')).rejects.toThrow(/permission denied/);
    await expect(execute(db.appUrl, 'SELECT count(*) FROM _prisma_migrations')).rejects.toThrow(/permission denied/);
  });
});

describe('test databases', () => {
  it('[US-007:AC5] should give every suite its own clean copy of the migrated database', async () => {
    const other = await createTestDatabase();
    try {
      await db.prisma.institution.create({ data: { name: 'Solo en esta suite', city: 'Neiva' } });

      expect(other.name).not.toBe(db.name);
      expect(await other.prisma.institution.count()).toBe(0);
    } finally {
      await other.dispose();
    }
  });
});
